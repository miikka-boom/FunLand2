// ICONS maps an id to the inner markup; icon(id) wraps it in an <svg>.

const O = '#15110d';
const NS = ' stroke="none"';

const p = (d, fill, ex = '') => `<path d="${d}" fill="${fill}"${ex}/>`;
const c = (cx, cy, r, fill, ex = '') => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill}"${ex}/>`;
const r = (x, y, w, h, fill, rx = 0, ex = '') => `<rect x="${x}" y="${y}" width="${w}" height="${h}"${rx ? ` rx="${rx}"` : ''} fill="${fill}"${ex}/>`;
const ln = (d, color, w = 1.4, ex = '') => `<path d="${d}" fill="none" stroke="${color}" stroke-width="${w}"${ex}/>`;
const hl = (d, w = 1.1) => ln(d, '#fff', w, ' stroke-opacity=".6"');
// A thick coloured stroke with a dark outline around it.
const os = (d, color, w) => ln(d, O, w + 2.6) + ln(d, color, w);
// Every icon gets the default outline, so elements only override it.
const g = (body) => `<g stroke="${O}" stroke-width="1.4" stroke-linejoin="round" stroke-linecap="round">${body}</g>`;

function gearPath(cx, cy, ro, ri, n, skip = -1) {
  const pts = [];
  const step = (Math.PI * 2) / n;
  for (let i = 0; i < n; i++) {
    const a = i * step - Math.PI / 2;
    if (i === skip) {
      // A broken tooth: jagged edge at the root radius.
      for (const [k, f] of [[-0.45, 0.98], [-0.15, 0.82], [0.1, 0.94], [0.35, 0.8]]) pts.push([cx + Math.cos(a + step * k) * ri * f, cy + Math.sin(a + step * k) * ri * f]);
      continue;
    }
    for (const [k, rad] of [[-0.36, ri], [-0.2, ro], [0.2, ro], [0.36, ri]]) pts.push([cx + Math.cos(a + step * k) * rad, cy + Math.sin(a + step * k) * rad]);
  }
  return 'M' + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'z';
}

