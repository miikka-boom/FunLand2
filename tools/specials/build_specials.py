#!/usr/bin/env python3
"""Build the special infected's models: the Tank and the Hunter, in the style of the artist's zombies.

Run it with a Python that has numpy and Pillow:
    python3 tools/specials/build_specials.py [--out DIR] [--game]

It writes, for each of them (tank, hunter), into tools/specials/models/:
  NAME.fbx   the model, laid out as the artist's zombies.fbx is (Blender's binary FBX 7.4, Y up,
             centimetres), a model per part with its origin at its joint
  NAME.png   its texture, 2048 px, with the zombies' palette strip where theirs is
  NAME.glb   the same model and texture in one glTF file, to open anywhere
and with --game, specials.js: the parts in the zombies' mesh format (assets/zombies/meshes.js), for
the game's sprite baker.
"""

import argparse
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import atlas  # noqa: E402
import export_files  # noqa: E402
import export_game  # noqa: E402
import hunter  # noqa: E402
import paint  # noqa: E402
import tank  # noqa: E402

ROOT = HERE.parents[1]


def baked(mat):
    return mat not in atlas.PAL_UV


class Built:
    """A figure with its outlines, UVs and texture."""

    def __init__(self, fig):
        self.fig = fig
        for part in fig.parts.values():
            shells = [pc.outline() for pc in part.pieces]
            part.all = part.pieces + [s for s in shells if s is not None]
        self.charts = []
        for part in fig.parts.values():
            for pc in part.pieces:
                self.charts += atlas.charts_for(part, pc, baked)
        self.density = atlas.pack_best(self.charts)
        self.uv = {}
        for ch in self.charts:
            for fi in ch.faces:
                for j in range(len(ch.piece.F[fi])):
                    self.uv[(id(ch.piece), fi, j)] = atlas.corner_uv(ch, fi, j, self.density)

    def uv_of(self, pc, fi, j):
        m = pc.mats[fi]
        if m in atlas.PAL_UV:
            return atlas.PAL_UV[m]
        return self.uv[(id(pc), fi, j)]

    def texture(self):
        S = atlas.SIZE
        x, y, P, N, ci = atlas.rasterize(self.charts, self.density)
        img = np.zeros((S, S, 3), dtype=np.float32)
        filled = np.zeros((S, S), dtype=bool)
        paint_fn = paint.painter(self.fig)
        for c_i, ch in enumerate(self.charts):
            m = ci == c_i
            if not m.any():
                continue
            img[y[m], x[m]] = paint_fn(ch.piece.mats[ch.faces[0]], P[m], N[m], ch.owner.name)
            filled[y[m], x[m]] = True
        pal = palette_strip()
        ph, pw = pal.shape[:2]
        img[:ph, :pw] = pal
        filled[:ph, :pw] = True
        return atlas.dilate(img, filled)


def palette_strip():
    """The zombies' palette strip: eye white, tan, dark red, black, at the top left (2048 px scale)."""
    S = atlas.SIZE
    h = int(round((1 - atlas.PALETTE_BOX[1]) * S))
    w = int(round(atlas.PALETTE_BOX[2] * S))
    img = np.zeros((h, w, 3), dtype=np.float32)
    img[:] = atlas.BACKGROUND
    x0, x1 = 34, 124
    for y0, y1, k in [(30, 146, "eye_white"), (146, 188, "tan"), (188, 246, "red"), (246, 292, "black")]:
        img[y0:y1, x0:x1] = atlas.PAL_RGB[k]
    return img


def game_module(builts):
    lines = [
        "// Generated by tools/specials/build_specials.py: do not edit by hand.",
        "// The special infected in the zombies' mesh format (see tools/specials/export_game.py).",
        f"export const POS_Q = {export_game.POS_Q};",
        f"export const PALETTE = {list(atlas.PALETTE_BOX)};",
    ]
    for b in builts:
        fig = b.fig
        parts = {}
        for name, part in fig.parts.items():
            mesh = export_game.encode(part.all, b.uv_of, eyes=(name == "head"))
            entry = {"at": [round(float(v), 2) for v in part.at], "pose": [round(float(v), 4) for v in part.pose], "mesh": mesh}
            if name == "head":
                entry["eyes"] = [{"mid": [round(float(v), 2) for v in e["mid"]], "half": [round(float(e["r"]), 2)] * 2} for e in fig.eyes]
            parts[name] = entry
            print(f"  {fig.name} {name}: {mesh['n']} verts, {mesh['tris']} tris, box {mesh['box']}")
        lines.append(f"export const {fig.name.upper()} = {export_game.js({'texture': fig.name + '.png', 'parts': parts})};")
    return "\n".join(lines) + "\n"


def build(out, game=False):
    out.mkdir(parents=True, exist_ok=True)
    builts = []
    for make in (tank.build, hunter.build):
        t0 = time.time()
        b = Built(make())
        name = b.fig.name
        tex = b.texture()
        Image.fromarray(tex, "RGB").save(out / f"{name}.png", optimize=True)
        export_files.write_fbx(out / f"{name}.fbx", b.fig, b.uv_of, f"{name}.png")
        export_files.write_glb(out / f"{name}.glb", b.fig, b.uv_of, (out / f"{name}.png").read_bytes())
        tris = sum(len(pc.tris()[0]) for part in b.fig.parts.values() for pc in part.all)
        print(f"{name}: {tris} triangles (outlines included), {len(b.charts)} charts at {b.density:.2f} texels a model unit, built in {time.time() - t0:.1f} s")
        builts.append(b)
    if game:
        (out / "specials.js").write_text(game_module(builts))
    return builts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "models"))
    ap.add_argument("--game", action="store_true", help="also write specials.js, the parts in the game's mesh format")
    a = ap.parse_args()
    build(Path(a.out), a.game)


if __name__ == "__main__":
    main()
