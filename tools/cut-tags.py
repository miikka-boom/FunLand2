"""Cut the hand-drawn spray tags out of a photo of the sketchbook page.

    python3 tools/cut-tags.py <photo.jpg>

Writes assets/tags/tags.png (white ink on transparent, packed) and
assets/tags/atlas.js (where each tag sits in it). Tags are found as clusters
of dark ink on the paper; each one is named by roughly where it sits on the
page (NAMES, in 1500-px-wide page coordinates), and only its own cluster's ink
is kept, so a neighbour's splatter never rides along.
"""
import numpy as np, sys, os
from PIL import Image, ImageFilter
from collections import deque
im = Image.open(sys.argv[1]).convert('L')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAXDIM = 192  # px on the longest side: plenty for a tag 60-90 world units long
W,H = im.size; f=4
small = im.resize((W//f,H//f), Image.BILINEAR)
Ls = np.asarray(small).astype(np.float32)
bgs = small.filter(ImageFilter.MaxFilter(15)).filter(ImageFilter.GaussianBlur(10))
ink = (Ls < np.asarray(bgs)*0.5) & (np.asarray(bgs) > 150)
dil = np.asarray(Image.fromarray(ink.astype(np.uint8)*255).filter(ImageFilter.MaxFilter(9))) > 0
h,w = dil.shape; lab=np.zeros((h,w),np.int32); n=0; comps={}
for y,x in zip(*np.nonzero(dil)):
    if lab[y,x]: continue
    n+=1; lab[y,x]=n; q=deque([(y,x)]); c=0
    while q:
        cy,cx=q.popleft(); c+=1
        for dy,dx in ((1,0),(-1,0),(0,1),(0,-1)):
            ny,nx=cy+dy,cx+dx
            if 0<=ny<h and 0<=nx<w and dil[ny,nx] and not lab[ny,nx]: lab[ny,nx]=n; q.append((ny,nx))
    comps[n]=c
boxes={}
for j in comps:
    yy,xx=np.nonzero(lab==j); boxes[j]=(xx.min(),yy.min(),xx.max(),yy.max())
# full-res background for alpha
L = np.asarray(im).astype(np.float32)
bg = np.asarray(bgs.resize((W,H), Image.BILINEAR)).astype(np.float32)
labF = np.asarray(Image.fromarray(lab.astype(np.int32)).resize((W,H), Image.NEAREST))
s = 1500/W
NAMES = { # by approximate centre in 1500-wide display coords
 'catarrow':(335,290),'bonesplat':(650,325),'helpus':(1030,375),'hope':(390,575),'catskull':(710,655),
 'deadbunny':(1035,710),'helloworld':(430,960),'housearrow':(815,955),'eyeslash':(1060,1060),
 'bigarrow':(400,1310),'cross':(755,1290),'bonesplat2':(1115,1490),'plus':(385,1690),'diagarrow':(740,1650),'thinarrow':(1070,1767)}
cut = {}
for name,(cx,cy) in NAMES.items():
    px,py = cx/s/f, cy/s/f
    k = max((j for j,b in boxes.items() if b[0]<=px<=b[2] and b[1]<=py<=b[3]), key=lambda j: comps[j])
    b = boxes[k]; x0,y0,x1,y1 = b[0]-2,b[1]-2,b[2]+3,b[3]+3
    sub = (lab[y0:y1,x0:x1]==k)
    # fill holes: background not reachable from the crop border
    hh,ww = sub.shape; outside=np.zeros_like(sub); q=deque()
    for yy in range(hh):
        for xx in (0,ww-1):
            if not sub[yy,xx] and not outside[yy,xx]: outside[yy,xx]=1; q.append((yy,xx))
    for xx in range(ww):
        for yy in (0,hh-1):
            if not sub[yy,xx] and not outside[yy,xx]: outside[yy,xx]=1; q.append((yy,xx))
    while q:
        cy,cx=q.popleft()
        for dy,dx in ((1,0),(-1,0),(0,1),(0,-1)):
            ny,nx=cy+dy,cx+dx
            if 0<=ny<hh and 0<=nx<ww and not sub[ny,nx] and not outside[ny,nx]: outside[ny,nx]=1; q.append((ny,nx))
    full = ~outside.astype(bool)
    mk = Image.fromarray((full*255).astype(np.uint8)).resize((ww*f,hh*f), Image.BILINEAR)
    m = np.asarray(mk) > 0
    oth = ((lab[y0:y1,x0:x1]>0) & (lab[y0:y1,x0:x1]!=k))
    om = Image.fromarray((oth*255).astype(np.uint8)).filter(ImageFilter.MaxFilter(3)).resize((ww*f,hh*f), Image.BILINEAR)
    keep = ~(np.asarray(om) > 0)
    X0,Y0 = x0*f,y0*f
    c = L[Y0:Y0+hh*f, X0:X0+ww*f]
    paper = np.percentile(c[~m] if (~m).sum()>100 else c, 60)
    a = np.clip((paper*0.62 - c) / (paper*0.37), 0, 1) * keep
    ys,xs = np.nonzero(a > 0.04); p=4
    a = a[ys.min()-p:ys.max()+p+1, xs.min()-p:xs.max()+p+1]
    img = Image.fromarray((a*255).astype(np.uint8))
    sc = MAXDIM / max(img.size)
    img = img.resize((max(1,round(img.width*sc)), max(1,round(img.height*sc))), Image.LANCZOS)
    cut[name] = img

# Shelf-pack into one sheet (2 px gutters so filtering never bleeds).
order = sorted(cut, key=lambda n: -cut[n].height)
SW, G = 1024, 2
x = y = shelf = 0; rects = {}
for n in order:
    im_ = cut[n]
    if x + im_.width + G > SW: x = 0; y += shelf + G; shelf = 0
    rects[n] = (x + G, y + G, im_.width, im_.height)
    x += im_.width + G; shelf = max(shelf, im_.height)
SH = y + shelf + 2 * G
alpha = Image.new('L', (SW, SH), 0)
for n, (rx, ry, rw, rh) in rects.items(): alpha.paste(cut[n], (rx, ry))
sheet = Image.new('LA', (SW, SH), 255); sheet.putalpha(alpha)
sheet.save(os.path.join(ROOT, 'assets/tags/tags.png'), optimize=True)
with open(os.path.join(ROOT, 'assets/tags/atlas.js'), 'w') as fh:
    fh.write('// Generated by tools/cut-tags.py: where each hand-drawn tag sits in\n')
    fh.write('// assets/tags/tags.png (white ink on transparent; tinted when drawn).\n\n')
    fh.write('export const TAG_ATLAS = {\n')
    for n in NAMES:
        fh.write(f'  {n}: [{", ".join(str(v) for v in rects[n])}],\n')
    fh.write('};\n')
print('sheet', SW, SH, os.path.getsize(os.path.join(ROOT, 'assets/tags/tags.png')), 'bytes')
